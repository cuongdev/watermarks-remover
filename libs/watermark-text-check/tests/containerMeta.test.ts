test("inspectContainer routes by filename and reports confidence", async () => {
  const report = await inspectContainer(enc.encode(MD), "post.md");
  assert.equal(report.format, "markdown");
  assert.equal(report.hasAiMetadata, true);
  assert.equal(report.findings.length, report.findingsConfidence.length);
});

test("finding confidence buckets match the Python heuristic", () => {
  assert.equal(classifyFindingConfidence("JPEG APP11 segment (JUMBF/C2PA common)"), "confirmed");
  assert.equal(classifyFindingConfidence("byte-scan C2PA markers: jumb"), "likely_false_positive");
  assert.equal(classifyFindingConfidence("info: cms generator: <meta ...>"), "informational");
  assert.equal(classifyFindingConfidence("frontmatter key: generator"), "probable");
  assert.equal(classifyFindingConfidence("XMP packet present"), "informational");
});
