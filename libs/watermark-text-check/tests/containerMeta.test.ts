async function buildOdt(): Promise<Uint8Array> {
  return writeZip([
    { name: "mimetype", data: enc.encode("application/vnd.oasis.opendocument.text") },
    { name: "content.xml", data: enc.encode("<office:text>hello</office:text>") },
    {
      name: "meta.xml",
      data: enc.encode(
        "<office:meta><meta:generator>Claude Code 2.0</meta:generator><dc:date>2026</dc:date></office:meta>",
      ),
    },
    { name: "styles.xml", data: enc.encode("<office:styles/>") },
  ]);
}

test("odt generator is flagged and removed", async () => {
  const report = await inspectOdt(await buildOdt());
  assert.equal(report.hasAi, true);

  const { data, actions } = await cleanOdt(await buildOdt());
  assert.ok(actions.includes("drop meta:generator"));
  const entries = await readZip(data);
  const meta = dec.decode(entries.find((e) => e.name === "meta.xml")!.data);
  assert.ok(!meta.includes("meta:generator"));
  assert.ok(meta.includes("dc:date"));
});

