const enc = new TextEncoder();
const dec = new TextDecoder();

// ---------------------------------------------------------------------------
// Markdown
// ---------------------------------------------------------------------------

const MD = `---
title: My Post
generator: Claude Code
tags:
  - one
  - two
---
Body text stays.
`;

test("markdown frontmatter generator key is flagged and removed", () => {
  const report = inspectMarkdown(MD);
  assert.equal(report.hasAi, true);
  assert.ok(report.findings.includes("frontmatter key: generator"));

  const { text, actions } = cleanMarkdown(MD);
  assert.ok(actions.includes("drop frontmatter key: generator"));
  assert.ok(text.includes("title: My Post"));
  assert.ok(text.includes("- two"));
  assert.ok(!text.includes("Claude"));
  assert.ok(text.includes("Body text stays."));
});

test("markdown without frontmatter is untouched", () => {
  const { text, actions } = cleanMarkdown("# Hello\n");
  assert.equal(text, "# Hello\n");
  assert.deepEqual(actions, ["no YAML frontmatter"]);
});

test("dropping every frontmatter key removes the block", () => {
  const md = "---\ngenerator: Claude\n---\nBody.\n";
  const { text, actions } = cleanMarkdown(md);
  assert.equal(text, "Body.\n");
  assert.ok(actions.includes("removed empty frontmatter block"));
});

// ---------------------------------------------------------------------------
// HTML
// ---------------------------------------------------------------------------

const HTML = `<html><head>
<meta charset="utf-8">
<meta name="generator" content="WordPress 6.4">
<meta name="generator" content="Claude by Anthropic">
<script type="application/ld+json">{"digitalSourceType":"trainedAlgorithmicMedia"}</script>
</head><body><p data-ai-model="claude">hi</p></body></html>`;

test("html AI generator flagged, CMS generator kept", () => {
  const report = inspectHtml(HTML);
  assert.equal(report.hasAi, true);
  assert.ok(report.findings.some((f) => f.startsWith("info: cms generator")));
  assert.ok(report.findings.some((f) => f.startsWith("meta:") && f.includes("Claude")));
  assert.ok(report.findings.includes("json-ld provenance-like block"));
  assert.ok(report.findings.some((f) => f.startsWith("attr: data-ai-model")));
});

test("html clean drops AI meta, keeps CMS generator", () => {
  const { text, actions } = cleanHtml(HTML);
  assert.ok(text.includes("WordPress 6.4"));
  assert.ok(!text.includes("Claude by Anthropic"));
  assert.ok(!text.includes("ld+json"));
  assert.ok(!text.includes("data-ai-model"));
  assert.ok(actions.some((a) => a.startsWith("drop meta:")));
  assert.ok(actions.includes("drop json-ld provenance-like script"));
});

// ---------------------------------------------------------------------------
// SVG
// ---------------------------------------------------------------------------

const SVG = `<svg xmlns="http://www.w3.org/2000/svg">
<metadata><rdf:RDF>c2pa manifest here</rdf:RDF></metadata>
<!-- generated by Claude -->
<rect width="1" height="1"/>
</svg>`;

test("svg metadata is flagged and removed", () => {
  const report = inspectSvg(enc.encode(SVG));
  assert.equal(report.hasC2pa, true);
  assert.ok(report.findings.includes("svg <metadata> present"));

  const { data, actions } = cleanSvg(enc.encode(SVG));
  const text = dec.decode(data);
  assert.ok(!text.includes("metadata"));
  assert.ok(!text.includes("Claude"));
  assert.ok(text.includes("<rect"));
  assert.ok(actions.some((a) => a.startsWith("drop <metadata>")));
  assert.ok(actions.includes("drop SVG comment with AI markers"));
});

// ---------------------------------------------------------------------------
// PDF (degraded stdlib mode)
// ---------------------------------------------------------------------------

const PDF = enc.encode(
  "%PDF-1.7\n1 0 obj<</Type/Catalog>>endobj\n" +
    '<?xpacket begin="x" id="W5M0"?><x:xmpmeta>digitalSourceType trainedAlgorithmicMedia</x:xmpmeta><?xpacket end="w"?>\n' +
    "stream\nAIGC-collision-bytes\nendstream\n%%EOF",
);

test("pdf xmp packet is flagged", () => {
  const report = inspectPdf(PDF);
  assert.equal(report.hasAi, true);
  assert.ok(report.findings.includes("XMP packet present"));
  // stream payload collisions are excluded from the structured scan
  assert.ok(!report.findings.some((f) => f.includes("AIGC-collision")));
});

test("pdf clean strips xpacket in degraded mode", () => {
  const { data, actions, meta } = cleanPdf(PDF);
  const text = dec.decode(data);
  assert.ok(!text.includes("xpacket"));
  assert.equal(meta["degraded"], true);
  assert.ok(actions.some((a) => a.startsWith("stripped XMP xpacket")));
});

test("pdf stream AIGC collisions do not flag structured scan", () => {
  const pdf = enc.encode("%PDF-1.7\nstream\nAIGC\nendstream\n%%EOF");
  const report = inspectPdf(pdf);
  assert.equal(report.hasAi, false);
});

// ---------------------------------------------------------------------------
// DOCX
// ---------------------------------------------------------------------------

async function buildDocx(): Promise<Uint8Array> {
  return writeZip([
    {
      name: "[Content_Types].xml",
      data: enc.encode(
        '<Types><Override PartName="/customXml/item1.xml" ContentType="application/xml"/><Default Extension="xml"/></Types>',
      ),
    },
    { name: "word/document.xml", data: enc.encode("<w:document><w:t>Claude is a name in the visible body</w:t></w:document>") },
    {
      name: "docProps/core.xml",
      data: enc.encode(
        "<cp:coreProperties><dc:creator>Claude</dc:creator><cp:lastModifiedBy>Someone</cp:lastModifiedBy></cp:coreProperties>",
      ),
    },
    {
      name: "docProps/app.xml",
      data: enc.encode("<Properties><Application>Anthropic Claude</Application></Properties>"),
    },
    { name: "customXml/item1.xml", data: enc.encode("<provenance>c2pa</provenance>") },
  ]);
}

test("zip roundtrip preserves entries", async () => {
  const zip = await buildDocx();
  const entries = await readZip(zip);
  assert.equal(entries.length, 5);
  const core = entries.find((e) => e.name === "docProps/core.xml");
  assert.ok(dec.decode(core!.data).includes("dc:creator"));
});

test("docx zip is detected by content sniff", async () => {
  const zip = await buildDocx();
  assert.equal(detectContainerFormat("report.docx", null), "docx");
  assert.equal(await detectZipContainerFormat(zip), "docx");
});

test("docx metadata parts are flagged, visible body ignored", async () => {
  const report = await inspectDocx(await buildDocx());
  assert.equal(report.hasAi, true);
  assert.ok(report.findings.some((f) => f.startsWith("docProps/core.xml:")));
  assert.ok(report.findings.some((f) => f.startsWith("customXml parts:")));
  assert.ok(!report.findings.some((f) => f.startsWith("word/document.xml")));
});

test("docx clean drops customXml and scrubs creator fields", async () => {
  const { data, actions } = await cleanDocx(await buildDocx());
  assert.ok(actions.includes("drop part customXml/item1.xml"));
  assert.ok(actions.includes("scrub docProps/core.xml field dc:creator"));
  assert.ok(actions.includes("scrub docProps/app.xml field Application"));
  assert.ok(actions.some((a) => a.startsWith("drop Content_Types customXml overrides")));

  const entries = await readZip(data);
  const names = entries.map((e) => e.name);
  assert.ok(!names.includes("customXml/item1.xml"));
  const core = dec.decode(entries.find((e) => e.name === "docProps/core.xml")!.data);
  assert.ok(core.includes("<dc:creator></dc:creator>"));
  assert.ok(core.includes("Someone")); // non AI field untouched
  const body = dec.decode(entries.find((e) => e.name === "word/document.xml")!.data);
  assert.ok(body.includes("visible body")); // body untouched
});

