import assert from "node:assert/strict";
import { test } from "node:test";

import {
  aggregate,
  auditItems,
  auditWebsite,
  guessKind,
  isActionable,
  parseSitemap,
  renderAuditReport,
  scanItem,
} from "../src/index.js";

const enc = new TextEncoder();

const PNG_WITH_TEXT = (() => {
  const ascii = (s: string) => [...s].map((c) => c.charCodeAt(0));
  const u32 = (v: number) => [(v >>> 24) & 0xff, (v >>> 16) & 0xff, (v >>> 8) & 0xff, v & 0xff];
  const chunk = (type: string, payload: number[]) => [
    ...u32(payload.length),
    ...ascii(type),
    ...payload,
    0,
    0,
    0,
    0,
  ];
  return new Uint8Array([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
    ...chunk("IHDR", new Array(13).fill(1)),
    ...chunk("tEXt", ascii("Generated by Claude")),
    ...chunk("IDAT", ascii("pix")),
    ...chunk("IEND", []),
  ]);
})();

test("scanItem normalizes text, image, and container items", async () => {
  const text = await scanItem("wa\u200Btermark", "note.txt");
  assert.equal(text.kind, "text");
  assert.equal(text.suspiciousTotal, 1);
  assert.ok(text.findings[0]!.startsWith("layer-a [zwj_family]"));
  assert.deepEqual(text.confidence, ["probable"]);

  const image = await scanItem(PNG_WITH_TEXT, "shot.png");
  assert.equal(image.kind, "png");
  assert.equal(image.hasAiMetadata, true);

  const md = await scanItem("---\ngenerator: Claude\n---\nBo\u200Bdy\n", "post.md");
  assert.equal(md.kind, "markdown");
  assert.equal(md.hasAiMetadata, true);
  assert.equal(md.suspiciousTotal, 1); // container plus Layer A body scan
  assert.ok(md.findings.some((f) => f.startsWith("frontmatter key:")));
  assert.ok(md.findings.some((f) => f.startsWith("layer-a [")));
});

test("aggregate and actionability match the Python heuristics", async () => {
  const items = [
    await scanItem("clean plain text", "a.txt"),
    await scanItem("wa\u200Btermark", "b.txt"),
    await scanItem(PNG_WITH_TEXT, "c.png"),
  ];
  const summary = aggregate(items);
  assert.equal(summary.total, 3);
  assert.equal(summary.byKind["text"], 2);
  assert.equal(summary.byKind["png"], 1);
  assert.equal(summary.withSuspiciousText, 1);
  assert.equal(summary.withAiMetadata, 1);
  assert.equal(summary.actionableFiles, 2);
  assert.equal(isActionable(items[0]!), false);
  assert.equal(isActionable(items[1]!), true);

  const rendered = renderAuditReport(items, summary, { Root: "/tmp/x" });
  assert.ok(rendered.startsWith("Root: /tmp/x"));
  assert.ok(rendered.includes("Actionable files: 2"));
  assert.ok(rendered.includes("[probable] b.txt: layer-a"));
});

test("auditItems skips oversized and broken items without aborting", async () => {
  const report = await auditItems(
    [
      { name: "ok.txt", data: "fine" },
      { name: "big.txt", data: "x".repeat(100), },
    ],
    { maxBytes: 50 },
  );
  assert.equal(report.itemsScanned, 1);
  assert.deepEqual(report.itemsSkipped, [{ path: "big.txt", reason: "too large" }]);
});

test("guessKind: content type, then suffix, then magic", () => {
  assert.equal(guessKind("https://x/a", new Uint8Array(), "text/html; charset=utf-8"), "html");
  assert.equal(guessKind("https://x/a.pdf", new Uint8Array()), "pdf");
  assert.equal(guessKind("https://x/a", enc.encode("%PDF-1.7")), "pdf");
  assert.equal(guessKind("https://x/a", enc.encode("<html><body>")), "html");
  assert.equal(guessKind("https://x/a", enc.encode("plain")), "text");
});

test("parseSitemap handles urlset and gzip", async () => {
  const xml = `<?xml version="1.0"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
    <url><loc>https://site.test/page1.html</loc></url>
    <url><loc> https://site.test/img.png </loc></url>
  </urlset>`;
  const plain = await parseSitemap(enc.encode(xml));
  assert.equal(plain.kind, "urlset");
  assert.deepEqual(plain.urls, ["https://site.test/page1.html", "https://site.test/img.png"]);

  const cs = new CompressionStream("gzip");
  const gz = new Uint8Array(
    await new Response(new Blob([enc.encode(xml)]).stream().pipeThrough(cs)).arrayBuffer(),
  );
  const zipped = await parseSitemap(gz);
  assert.deepEqual(zipped.urls, plain.urls);
});

test("auditWebsite end to end with an injected fetch", async () => {
  const pages: Record<string, { body: Uint8Array | string; type: string }> = {
    "https://site.test/sitemap.xml": {
      body: `<urlset><url><loc>https://site.test/index.html</loc></url><url><loc>https://site.test/logo.png</loc></url></urlset>`,
      type: "application/xml",
    },
    "https://site.test/index.html": {
      body: '<html><head><meta name="generator" content="Claude by Anthropic"></head></html>',
      type: "text/html",
    },
    "https://site.test/logo.png": { body: PNG_WITH_TEXT, type: "image/png" },
  };
  const fakeFetch = (async (url: RequestInfo | URL) => {
    const page = pages[String(url)];
    if (!page) return new Response("nf", { status: 404 });
    const body = typeof page.body === "string" ? enc.encode(page.body) : page.body;
    return new Response(body as BodyInit, {
      status: 200,
      headers: { "Content-Type": page.type },
    });
  }) as typeof fetch;

  const report = await auditWebsite({
    sitemapUrl: "https://site.test/sitemap.xml",
    fetchImpl: fakeFetch,
  });
  assert.equal(report.urlsCollected, 2);
  assert.equal(report.urlsScanned, 2);
  assert.equal(report.urlsFailed.length, 0);
  assert.equal(report.summary.actionableFiles, 2);
  const html = report.items.find((i) => i.kind === "html")!;
  assert.equal(html.path, "https://site.test/index.html");
  assert.ok(html.findings.some((f) => f.startsWith("meta:")));
});

test("auditWebsite records failures and keeps going", async () => {
  const fakeFetch = (async (url: RequestInfo | URL) => {
    const u = String(url);
    if (u.endsWith("sitemap.xml")) {
      return new Response(
        "<urlset><url><loc>https://site.test/ok.txt</loc></url><url><loc>https://site.test/missing</loc></url></urlset>",
        { status: 200 },
      );
    }
    if (u.endsWith("ok.txt")) return new Response("hello", { status: 200 });
    return new Response("nf", { status: 404 });
  }) as typeof fetch;

  const report = await auditWebsite({
    sitemapUrl: "https://site.test/sitemap.xml",
    fetchImpl: fakeFetch,
  });
  assert.equal(report.urlsScanned, 1);
  assert.equal(report.urlsFailed.length, 1);
  assert.match(report.urlsFailed[0]!.error, /404/);
});

test("fetch is capped and non http URLs are refused", async () => {
  const fakeFetch = (async () => new Response("x".repeat(100), { status: 200 })) as typeof fetch;
  const { fetchCapped } = await import("../src/index.js");
  await assert.rejects(
    fetchCapped("https://site.test/big", { maxBytes: 10, fetchImpl: fakeFetch }),
    /exceeds 10 bytes/,
  );
  await assert.rejects(fetchCapped("file:///etc/passwd", { fetchImpl: fakeFetch }), /non-http/);
});
