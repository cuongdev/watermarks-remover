/**
 * Classify a scanner finding by confidence. Heuristic and intentionally
 * conservative; a scanner finding is a signal, not a verdict.
 *
 * confirmed: recognized provenance structure (C2PA/JUMBF manifest, parsed
 * digitalSourceType / trainedAlgorithmicMedia fields).
 * probable: AI/vendor marker inside a recognized metadata structure.
 * informational: context only notes (CMS generators, XMP packet presence).
 * likely_false_positive: raw whole file byte scans that can collide with
 * compressed image/stream data.
 */
export function classifyFindingConfidence(finding: string): FindingConfidence {
  const t = finding.toLowerCase();
  if (CONFIRMED_SUBSTRINGS.some((s) => t.includes(s))) return "confirmed";
  if (t.startsWith("info:") || INFORMATIONAL_SUBSTRINGS.some((s) => t.includes(s))) {
    return "informational";
  }
  if (t.includes("byte-scan")) return "likely_false_positive";
  if (PROBABLE_SUBSTRINGS.some((s) => t.includes(s))) return "probable";
  return "informational";
}

// ---------------------------------------------------------------------------
// Byte/string helpers shared by the binary format inspectors.
// Latin-1 gives a lossless 1:1 byte to char mapping, so regex offsets on the
// decoded string map straight back to byte offsets.
// ---------------------------------------------------------------------------

export function bytesToLatin1(data: Uint8Array): string {
  const parts: string[] = [];
  const CHUNK = 0x8000;
  for (let i = 0; i < data.length; i += CHUNK) {
    parts.push(String.fromCharCode(...data.subarray(i, i + CHUNK)));
  }
  return parts.join("");
}

export function latin1ToBytes(text: string): Uint8Array {
  const out = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i += 1) out[i] = text.charCodeAt(i) & 0xff;
  return out;
}

export function utf8Encode(text: string): Uint8Array {
  return new TextEncoder().encode(text);
}

export function utf8Decode(data: Uint8Array): string {
  return new TextDecoder("utf-8", { fatal: false }).decode(data);
}

/**
 * Port of image_meta._contains_any: case insensitive needle scan over a blob
 * (given here as its latin-1 decoded string). Returns the needles found.
 */
export function containsAny(blobLatin1: string, needles: readonly string[]): string[] {
  const lower = blobLatin1.toLowerCase();
  const found: string[] = [];
  for (const n of needles) {
    if (lower.includes(n.toLowerCase())) found.push(n);
  }
  return found;
}

/** Port of container_meta._blob_hits. */
export function blobHits(blobLatin1: string): {
  hasC2pa: boolean;
  hasAi: boolean;
  findings: string[];
} {
  const lower = blobLatin1.toLowerCase();
  const findings: string[] = [];
  let hasC2pa = false;
  let hasAi = false;
  for (const n of C2PA_MARKERS) {
    if (lower.includes(n.toLowerCase())) {
      hasC2pa = true;
      findings.push(`marker:${n}`);
    }
  }
  const seen = new Set(findings.map((f) => f.split(":").slice(1).join(":")));
  for (const n of AI_META_HINTS) {
    if (lower.includes(n.toLowerCase())) {
      hasAi = true;
      if (!seen.has(n)) findings.push(`ai:${n}`);
    }
  }
  return { hasC2pa, hasAi: hasAi || hasC2pa, findings: findings.slice(0, 30) };
}
